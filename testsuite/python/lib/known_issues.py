# The failure of a coredump found by the module teardown, followed by its path
COREDUMP_DETECTED = "Coredump detected: "


def analyze_coredump(coredump):
    """
    Return the evidence of a coredump to classify it, as {"path", "bin_path",
    "slurm_prefix", "bt_file", "bt", "error"}, where path is its new path.

    The coredump is moved into the logs dir, and gdb is run on it to get its
    binary and to save its full backtrace in bt_file. If its binary cannot be
    found, bin_path is None and error explains why.

    The analysis is kept in atf.properties["coredumps"] for its original and
    its new path, so gdb only runs once for each coredump.
    """
    coredumps = atf.properties["coredumps"]
    if coredump in coredumps:
        return coredumps[coredump]

    orig_coredump = coredump

    # Ensure that the core is copied into the logs dir
    if atf.properties["slurm-logs-dir"] not in coredump:
        coredump_new = (
            f"{atf.properties['slurm-logs-dir']}/{os.path.basename(coredump)}"
        )
        logging.debug(f"Moving coredump from {coredump} to {coredump_new}")
        atf.run_command(f"mv {coredump} {coredump_new}", user="root", quiet=True)
        coredump = coredump_new

    # Get the binary that generated the coredump using gdb's
    # "info auxv": AT_EXECFN is the kernel-recorded full path of the
    # executable. Avoids 'file' command issues with cores having "too
    # many program headers".
    # debuginfod off: It may be too slow
    # Use atf.resolve_core_binary() to avoid issue with upgraded
    # components
    gdb_res = atf.run_command(
        f"gdb"
        f" -batch"
        f' -iex "set debuginfod enabled off"'
        f" -c {coredump}"
        f' -ex "info auxv"'
        f' -ex "quit"',
        user="root",
        quiet=True,
        timeout=300,
    )
    if gdb_res["exit_code"] != 0:
        logging.warning(
            f"Error getting the binary from the coredump: {gdb_res['exit_code']}"
        )
    gdb_out = gdb_res["stdout"] + gdb_res["stderr"]
    bin_match = re.search(r'AT_EXECFN.*?"([^"\n]+)"', gdb_out) or re.search(
        r"Core was generated by [`']([^ '`\n]+)", gdb_out
    )

    execfn_path = bin_match.group(1) if bin_match else None
    bin_path = atf.resolve_core_binary(coredump, execfn_path) if execfn_path else None

    if not bin_path:
        if not execfn_path:
            logging.warning(f"Unable to get the binary of {coredump}: {gdb_out}")
            error = "unable to get binary from gdb"
        else:
            error = f"unable to resolve binary by build-id (AT_EXECFN={execfn_path})"
        analysis = {
            "path": coredump,
            "bin_path": None,
            "slurm_prefix": None,
            "bt_file": None,
            "bt": "",
            "error": error,
        }
    else:
        # Generate the .bt file if binary was found
        bt_file = f"{coredump}.bt"
        logging.debug(
            f"Saving the full backtrace of {coredump} from {bin_path} into {bt_file}"
        )
        # debuginfod off: It may be too slow
        results = atf.run_command(
            f"gdb"
            f" -batch"
            f' -iex "set debuginfod enabled off"'
            f' -ex "info files"'
            f' -ex "set pagination off"'
            f' -ex "set confirm off"'
            f' -ex "set print pretty on"'
            f' -ex "set max-value-size unlimited"'
            f' -ex "set print array-indexes on"'
            f' -ex "set print array off"'
            f' -ex "thread apply all bt full"'
            f' -ex "quit"'
            f" {bin_path} {coredump}",
            user="root",
            quiet=True,
            timeout=300,
        )
        if results["exit_code"] != 0:
            logging.warning(f"Error generating the bt file: {results['exit_code']}")
        with open(bt_file, "w") as f:
            f.write(results["stdout"])
            f.write(results["stderr"])

        analysis = {
            "path": coredump,
            "bin_path": bin_path,
            "slurm_prefix": os.path.dirname(os.path.dirname(bin_path)),
            "bt_file": bt_file,
            "bt": results["stdout"] + results["stderr"],
            "error": None,
        }

    coredumps[orig_coredump] = coredumps[coredump] = analysis
    return analysis


def _related_coredumps(failure):
    """
    Return the analysis of the coredumps that may explain a failure:
    - The coredump of a COREDUMP_DETECTED failure.
    - The coredumps of the components that may cause a teardown failure (see
      TEARDOWN_SIDE_EFFECTS).
    - The coredumps of the binary of a command that was expected to fail but
      succeeded. The expect tests (run_command in globals) see a command killed
      by a signal as a success, e.g. a client that crashes at exit after
      failing as expected.
    Other failures have no related coredumps, so gdb is not run for them.
    """
    if failure.startswith(COREDUMP_DETECTED):
        return [analyze_coredump(failure[len(COREDUMP_DETECTED) :])]

    match = re.search(
        r'Command "(\S+)[^"]*" was expected to fail but succe+ded', failure
    )
    if match:
        binary = os.path.basename(match.group(1))
        related = []
        for coredump in atf.get_coredumps():
            analysis = analyze_coredump(coredump)
            if (
                analysis["bin_path"]
                and os.path.basename(analysis["bin_path"]) == binary
            ):
                related.append(analysis)
        return related

    components = [
        component
        for component, side_effects in TEARDOWN_SIDE_EFFECTS.items()
        if any(side_effect in failure for side_effect in side_effects)
    ]
    if not components:
        return []

    related = []
    for coredump in atf.get_coredumps():
        analysis = analyze_coredump(coredump)
        if analysis["bin_path"] and any(
            analysis["bin_path"].endswith(component) for component in components
        ):
            related.append(analysis)
    return related


