@dataclass(frozen=True)
class GresCfgCase:
    test_id: str
    slurm_conf_gres: str
    gres_conf: str
    fake_gpus_conf: str
    expected_output: tuple[str, ...]
    err_regex: str = ""
    expected_errs: int = 0

    @property
    def requires_nvml(self):
        return self.test_id in NVML_CASES

    @property
    def expect_fatal(self):
        return self.test_id in FATAL_CASES


def _case(
    test_id,
    slurm_conf_gres,
    gres_conf,
    fake_gpus_conf,
    expected_output,
    err_regex="",
    expected_errs=0,
):
    return GresCfgCase(
        test_id,
        slurm_conf_gres,
        gres_conf,
        fake_gpus_conf,
        tuple(
            line
            for line in expected_output.splitlines()
            if line.startswith("GRES_PARSABLE")
        ),
        err_regex,
        int(expected_errs),
    )


