def _is_nvml_build():
    config_h = pathlib.Path(atf.properties["slurm-build-dir"]) / "config.h"
    if not config_h.exists():
        return False
    return bool(re.search(r"^#define\s+HAVE_NVML\s+1$", config_h.read_text(), re.M))


