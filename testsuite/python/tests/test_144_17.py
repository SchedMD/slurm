@pytest.mark.parametrize("case", _case_params())
def test_gres_device_merge(environment, case):
    """Test gres.conf records merged with detected GPU devices."""
    test_program, test_dir = environment
    device_prefix = str(test_dir / "nvidia")
    (test_dir / "gres.conf").write_text(
        case.gres_conf.replace("DEV_PREFIX", device_prefix)
    )
    (test_dir / "fake_gpus.conf").write_text(
        case.fake_gpus_conf.replace("DEV_PREFIX", device_prefix)
    )

    result = atf.run_command(
        shlex.join(
            [str(test_program), str(test_dir), "tux0", case.slurm_conf_gres, "3"]
        ),
    )
    stderr = result["stderr"]

    actual_output = re.findall(r"GRES_PARSABLE\S+", stderr)
    expected_output = [
        line.replace("DEV_PREFIX", device_prefix) for line in case.expected_output
    ]
    assert actual_output == expected_output, (
        f"{case.test_id}: GRES_PARSABLE output mismatch\n"
        f"actual: {actual_output!r}\nexpected: {expected_output!r}\n"
        f"stderr:\n{stderr}"
    )

    if case.err_regex:
        actual_errs = len(re.findall(case.err_regex, stderr))
        assert actual_errs == case.expected_errs, (
            f"{case.test_id}: expected {case.expected_errs} matches of "
            f"{case.err_regex!r}, got {actual_errs}\nstderr:\n{stderr}"
        )

    if case.expect_fatal:
        assert (
            result["exit_code"] != 0
        ), f"{case.test_id}: expected a nonzero exit code\nstderr:\n{stderr}"
    else:
        assert result["exit_code"] == 0, (
            f"{case.test_id}: unexpected exit code {result['exit_code']}\n"
            f"stderr:\n{stderr}"
        )
